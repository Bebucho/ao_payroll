import frappe
from frappe import _


def block_payroll_journal_cancellation(doc, method=None):
    """
    Prevent independent cancellation of a Journal Entry generated
    by a submitted Payroll Entry.
    """

    payroll_entries = frappe.get_all(
        "Journal Entry Account",
        filters={
            "parent": doc.name,
            "parenttype": "Journal Entry",
            "reference_type": "Payroll Entry",
        },
        pluck="reference_name",
        distinct=True,
    )

    if not payroll_entries:
        return

    for payroll_entry in payroll_entries:
        docstatus = frappe.db.get_value(
            "Payroll Entry",
            payroll_entry,
            "docstatus",
        )

        if docstatus == 1:
            frappe.throw(
                _(
                    "Journal Entry {0} was generated by submitted "
                    "Payroll Entry {1} and cannot be cancelled independently. "
                    "Cancel the Payroll Entry instead."
                ).format(
                    frappe.bold(doc.name),
                    frappe.bold(payroll_entry),
                )
            )
